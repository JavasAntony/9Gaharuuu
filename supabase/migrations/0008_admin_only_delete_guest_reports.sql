-- KelasKita v2 follow-up: two policy changes with a matching schema change.
--
-- 1. Deletion belongs to the admin dashboard and nowhere else.
--
--    Until now an owner could delete their own post or comment straight from the
--    feed, because `grant delete` plus the "owners or admins delete" policy let
--    any authenticated caller remove their own row. This drops the owner branch
--    and the grant, so the ONLY path to a deletion is `public.hapus_konten`,
--    which re-checks the role, stamps `moderation_logs`, and is what the
--    dashboard calls.
--
--    `private.owns_post()` and `private.owns_comment()` are kept: they are the
--    ownership primitives this schema is built on, and they still document what
--    "yours" means. They simply no longer back a policy.
--
-- 2. Any member can report any content, guest or member.
--
--    A report names one `posts.id` or one `comments.id`, and guest content lives
--    in `guest_posts` / `guest_comments`, so until now reporting guest content
--    raised P0002. That made anonymous posts the one thing nobody could hold to
--    account, which is the opposite of what a report button is for. `buat_laporan`
--    now resolves a target in either table, and `admin_reports` resolves it back
--    the same way for the moderator.
--
--    Nothing about anonymity weakens: the guest tables have no author column, so
--    a report on guest content resolves to NULL author, exactly as an anonymous
--    member post does. The dashboard shows "no account behind this content"
--    rather than inventing one.

-- ---------------------------------------------------------------------------
-- 1. Deletion is admin-only
-- ---------------------------------------------------------------------------

drop policy "owners or admins delete posts" on public.posts;
create policy "admins delete posts" on public.posts
  for delete to authenticated
  using ((select private.is_admin()));

drop policy "owners or admins delete comments" on public.comments;
create policy "admins delete comments" on public.comments
  for delete to authenticated
  using ((select private.is_admin()));

-- The policies above are the real boundary; the grant goes too so a caller that
-- tries a direct DELETE gets 42501 rather than a silent zero-row update that
-- looks like it worked. `public.hapus_konten` is `security definer`, so the
-- dashboard is unaffected.
revoke delete on table public.posts from authenticated;
revoke delete on table public.comments from authenticated;

-- ---------------------------------------------------------------------------
-- 2. A report may target guest content
-- ---------------------------------------------------------------------------

-- Same signature, so the grants below are unchanged. A target is accepted when it
-- exists in EITHER table, and the two can never collide: both ids are primary
-- keys of different tables and a guest id is generated by the client.
create or replace function public.buat_laporan(
  p_post_id uuid,
  p_comment_id uuid,
  p_reason text,
  p_description text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reporter uuid := (select auth.uid());
begin
  if v_reporter is null then
    raise exception 'Hanya anggota kelas yang bisa melapor'
      using errcode = '42501';
  end if;

  if (p_post_id is null) = (p_comment_id is null) then
    raise exception 'Laporan harus menunjuk tepat satu konten'
      using errcode = '22023';
  end if;

  if p_reason is null or p_reason not in (
    'spam', 'harassment', 'bullying', 'inappropriate', 'hate', 'other'
  ) then
    raise exception 'Alasan laporan tidak dikenal'
      using errcode = '22023';
  end if;

  if p_description is not null and char_length(p_description) > 1000 then
    raise exception 'Keterangan laporan terlalu panjang'
      using errcode = '22023';
  end if;

  -- The target must exist, as a member row or a guest row. It cannot be a post
  -- the reporter is not allowed to see, because every member reads every post
  -- anyway.
  if p_post_id is not null
     and not exists (
       select 1 from public.posts p where p.id = p_post_id
       union all
       select 1 from public.guest_posts g where g.id = p_post_id
     ) then
    raise exception 'Postingan tidak ditemukan'
      using errcode = 'P0002';
  end if;

  if p_comment_id is not null
     and not exists (
       select 1 from public.comments c where c.id = p_comment_id
       union all
       select 1 from public.guest_comments gc where gc.id = p_comment_id
     ) then
    raise exception 'Komentar tidak ditemukan'
      using errcode = 'P0002';
  end if;

  begin
    insert into public.reports (reporter_id, post_id, comment_id, reason, description)
    values (v_reporter, p_post_id, p_comment_id, p_reason, nullif(btrim(p_description), ''));
  exception
    -- Already reported this exact target: idempotent, not an error.
    when unique_violation then
      return;
  end;
end;
$$;

revoke execute on function public.buat_laporan(uuid, uuid, text, text) from public, anon;
grant execute on function public.buat_laporan(uuid, uuid, text, text) to authenticated;

-- The moderator's view of the same target.
--
-- `report_type` now names the table the content actually lives in, because the
-- dashboard hands it straight to `public.hapus_konten` as `p_kind`:
--
--   'post' | 'comment'          member content
--   'guest_post' | 'guest_comment'   guest content, still in the database
--
-- A target that has since been deleted falls back to 'post' or 'comment' from
-- the column that was set, which is only ever used to disable the delete button.
create or replace view public.admin_reports with (security_invoker = false) as
  select
    r.id,
    r.reason,
    r.description,
    r.status,
    r.created_at,
    r.resolved_at,
    r.post_id,
    r.comment_id,
    case
      when r.post_id is not null and gp.id is not null then 'guest_post'
      when r.post_id is not null then 'post'
      when gc.id is not null then 'guest_comment'
      else 'comment'
    end::text as report_type,
    coalesce(p.content, c.content, gp.content, gc.content)::text as content_text,
    coalesce(p.anonymous, c.anonymous, true) as content_anonymous,
    coalesce(p.created_at, c.created_at, gp.created_at, gc.created_at) as content_created_at,
    -- Real author, for moderation. Null when the content is already gone, and
    -- always null for guest content: those rows have no author to point at.
    pa.id as content_author_id,
    pa.username as content_author_username,
    ca.id as comment_author_id,
    ca.username as comment_author_username,
    reporter.username as reporter_username,
    resolver.username as resolver_username
  from public.reports r
  left join public.posts p on p.id = r.post_id
  left join public.profiles pa on pa.id = p.user_id
  left join public.guest_posts gp on gp.id = r.post_id
  left join public.comments c on c.id = r.comment_id
  left join public.profiles ca on ca.id = c.user_id
  left join public.guest_comments gc on gc.id = r.comment_id
  left join public.profiles reporter on reporter.id = r.reporter_id
  left join public.profiles resolver on resolver.id = r.resolved_by
  where (select private.is_admin());

-- The two guest lists are no longer the only route to guest content -- it can be
-- reported now -- but they stay: a report is something somebody chose to file,
-- while these are the sweep for everything nobody bothered to report.
revoke all on public.admin_reports from anon;
grant select on public.admin_reports to authenticated;